import React from 'react';
import {
  AlertOctagon,
  FileCode,
  CheckCircle2,
  AlertTriangle,
  Layers,
  Sparkles,
  Info,
} from 'lucide-react';
import { DiagnosisResult } from '../../shared/types.js';

interface DiagnosisCardProps {
  diagnosis: DiagnosisResult;
}

export const DiagnosisCard: React.FC<DiagnosisCardProps> = ({ diagnosis }) => {
  const {
    headline,
    summary,
    confidenceScore,
    evidence,
    rootCauses,
    modelUsed,
    isDemo,
    safetyNotice,
  } = diagnosis;

  const confidencePct = Math.round((confidenceScore || 0.85) * 100);

  return (
    <div className="space-y-6">
      {/* Demo Watermark Banner if applicable */}
      {isDemo && (
        <div className="flex items-center gap-2 p-3.5 rounded-xl bg-amber-950/40 border border-amber-800/60 text-amber-300 text-xs font-semibold shadow-sm">
          <Sparkles className="h-4 w-4 shrink-0 text-amber-400" />
          <span>
            [DEMO / SAMPLE DATA - NO LIVE MODEL CONNECTED] This diagnostic result was generated by the deterministic offline engine for demonstration purposes.
          </span>
        </div>
      )}

      {/* Main Diagnosis Card */}
      <div className="rounded-2xl border border-slate-800 bg-slate-900/80 p-6 shadow-xl backdrop-blur-sm">
        {/* Header */}
        <div className="flex flex-col md:flex-row md:items-start md:justify-between gap-4 pb-5 border-b border-slate-800">
          <div>
            <div className="flex items-center gap-2 text-xs text-indigo-400 font-semibold uppercase tracking-wider mb-1.5">
              <AlertOctagon className="h-4 w-4" />
              <span>Diagnostic Assessment</span>
            </div>
            <h2 className="text-xl font-bold text-white tracking-tight">
              {headline}
            </h2>
            <p className="text-sm text-slate-300 mt-2 leading-relaxed">
              {summary}
            </p>
          </div>

          {/* Confidence Score Pill */}
          <div className="shrink-0 flex flex-col items-end">
            <div className="flex items-center gap-2 px-3 py-1.5 rounded-xl bg-slate-950 border border-slate-800">
              <span className="text-xs text-slate-400 font-medium">Confidence:</span>
              <span
                className={`text-xs font-bold ${
                  confidencePct >= 80
                    ? 'text-emerald-400'
                    : confidencePct >= 60
                    ? 'text-amber-400'
                    : 'text-rose-400'
                }`}
              >
                {confidencePct}%
              </span>
            </div>
            <span className="text-[10px] text-slate-500 mt-1 font-mono">
              Engine: {modelUsed}
            </span>
          </div>
        </div>

        {/* Extracted Evidence Section */}
        <div className="mt-5 space-y-3">
          <div className="flex items-center justify-between">
            <h3 className="text-xs font-semibold uppercase tracking-wider text-slate-400 flex items-center gap-1.5">
              <FileCode className="h-4 w-4 text-slate-400" />
              <span>Visible Evidence Extracted from Screenshot</span>
            </h3>

            {evidence.uncertain && (
              <span className="flex items-center gap-1 text-[11px] font-medium text-amber-400 bg-amber-950/40 px-2 py-0.5 rounded-full border border-amber-800/40">
                <AlertTriangle className="h-3 w-3" />
                Uncertain / Blurry Visual Evidence
              </span>
            )}
          </div>

          {/* Raw snippet block */}
          {evidence.rawText && (
            <div className="relative rounded-xl bg-slate-950 border border-slate-800 p-3.5 font-mono text-xs text-slate-300 overflow-x-auto max-h-48">
              <pre className="whitespace-pre-wrap leading-relaxed">{evidence.rawText}</pre>
            </div>
          )}

          {/* Evidence metadata tags */}
          <div className="flex flex-wrap gap-2 text-xs">
            {evidence.errorType && (
              <span className="px-2.5 py-1 rounded-lg bg-slate-800/80 border border-slate-700/60 text-slate-300">
                <strong className="text-slate-400">Type:</strong> {evidence.errorType}
              </span>
            )}
            {evidence.errorCode && (
              <span className="px-2.5 py-1 rounded-lg bg-slate-800/80 border border-slate-700/60 text-slate-300">
                <strong className="text-slate-400">Code:</strong> {evidence.errorCode}
              </span>
            )}
            {evidence.filePath && (
              <span className="px-2.5 py-1 rounded-lg bg-slate-800/80 border border-slate-700/60 text-slate-300 font-mono">
                <strong className="text-slate-400">File:</strong> {evidence.filePath}
                {evidence.lineNumber && `:${evidence.lineNumber}`}
              </span>
            )}
            {evidence.suspectComponent && (
              <span className="px-2.5 py-1 rounded-lg bg-slate-800/80 border border-slate-700/60 text-slate-300">
                <strong className="text-slate-400">Component:</strong> {evidence.suspectComponent}
              </span>
            )}
          </div>
        </div>

        {/* Ranked Root Causes */}
        {rootCauses && rootCauses.length > 0 && (
          <div className="mt-6 pt-5 border-t border-slate-800 space-y-3">
            <h3 className="text-xs font-semibold uppercase tracking-wider text-slate-400 flex items-center gap-1.5">
              <Layers className="h-4 w-4 text-slate-400" />
              <span>Ranked Root Cause Hypotheses</span>
            </h3>

            <div className="space-y-2.5">
              {rootCauses.map((rc, idx) => {
                const probPct = Math.round((rc.probability || 0.5) * 100);
                return (
                  <div
                    key={idx}
                    className="p-3.5 rounded-xl bg-slate-950/60 border border-slate-800/80 space-y-1.5"
                  >
                    <div className="flex items-center justify-between text-xs">
                      <span className="font-semibold text-slate-200">
                        {idx + 1}. {rc.cause}
                      </span>
                      <span className="font-mono text-indigo-400 font-bold">
                        {probPct}% Likelihood
                      </span>
                    </div>

                    {/* Progress bar */}
                    <div className="w-full bg-slate-800 h-1.5 rounded-full overflow-hidden">
                      <div
                        className="bg-indigo-500 h-full rounded-full transition-all duration-500"
                        style={{ width: `${probPct}%` }}
                      />
                    </div>

                    <p className="text-xs text-slate-400 leading-relaxed">
                      {rc.explanation}
                    </p>
                  </div>
                );
              })}
            </div>
          </div>
        )}

        {/* Safety Notice Footer */}
        {safetyNotice && (
          <div className="mt-5 p-3 rounded-xl bg-slate-950 border border-slate-800/80 flex items-start gap-2 text-xs text-slate-400">
            <Info className="h-4 w-4 text-slate-500 shrink-0 mt-0.5" />
            <span>{safetyNotice}</span>
          </div>
        )}
      </div>
    </div>
  );
};
